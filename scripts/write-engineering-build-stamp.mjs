#!/usr/bin/env node
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const sha = (
  process.env.EDUVIJNA_GIT_SHA ||
  spawnSync('git', ['rev-parse', 'HEAD'], { cwd: repoRoot, encoding: 'utf8' }).stdout ||
  ''
).trim();
const outDir = join(repoRoot, 'src', 'generated');
mkdirSync(outDir, { recursive: true });
const outFile = join(outDir, 'engineeringImplementationSha.ts');
const content = `/** Auto-generated by scripts/write-engineering-build-stamp.mjs — do not edit. */
export const ENGINEERING_IMPLEMENTATION_SHA = '${sha}';
`;
writeFileSync(outFile, content, 'utf8');
console.log(JSON.stringify({ wrote: outFile, sha }));
